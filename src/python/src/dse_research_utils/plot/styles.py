def set_matplotlib_default_style() -> None:
    """Applies the default custom matplotlib style dictionary.

    ``font.family`` is then set from :func:`default_font_families`, so plain text
    draws the symbols Noto Sans lacks from Noto Sans Math where it is installed.
    Like any rcParam, the setting applies to text created after the call.
    """
    plt.style.use(DEFAULT_STYLE_DICT)
    plt.rcParams["font.family"] = default_font_families()


def default_font_families() -> list[str]:
    """Return the ``font.family`` list for the default style on this machine.

    matplotlib falls back to another font glyph by glyph only across the families
    named in ``font.family``, and resolves the generic ``"sans-serif"`` to a single
    font: the first installed entry of ``font.sans-serif``. Noto Sans has no
    arrows, mathematical operators, technical symbols, geometric shapes or
    dingbats, so the list continues with Noto Sans Math, which is designed to pair
    with it, and then DejaVu Sans, which ships with matplotlib.

    Noto Sans Math is listed only when it is installed, because matplotlib logs a
    warning every time it lays out text with a named family it cannot find.

    Returns
    -------
    list[str]
        ``["sans-serif", "Noto Sans Math", "DejaVu Sans"]``, or
        ``["sans-serif", "DejaVu Sans"]`` when Noto Sans Math is not installed.
    """
    families = ["sans-serif"]
    if _font_family_installed(FONT_FAMILY_MATH):
        families.append(FONT_FAMILY_MATH)
    families.append(FONT_FAMILY_FALLBACK)
    return families


def _font_family_installed(family: str) -> bool:
    # A list, because FontProperties parses a lone string as a fontconfig pattern.
    try:
        font_manager.findfont(font_manager.FontProperties(family=[family]), fallback_to_default=False)
    except ValueError:
        return False
    return True


def categorical_palette(n: int, palette: str | None = None) -> list:
    """Return ``n`` colours for categorical series.

    By default these are the first ``n`` of :data:`CHART_COLOURS`, as hex
    strings. The DSE design language allows at most six categorical series, so a
    larger ``n`` raises ``ValueError``: group the smallest categories, split the
    figure into small multiples or label each series directly.

    A named matplotlib ``palette`` is for figures outside the design language,
    and returns RGBA tuples. Colormaps with fewer than 256 entries cycle when
    ``n`` exceeds their size, so colours can repeat. Colormaps with at least 256
    entries are sampled evenly from 0 to 1, including endpoints when ``n > 1``.
    A single colour uses 0.

    Parameters
    ----------
    n : int
        Number of series.
    palette : str, optional
        A matplotlib colormap name, in place of the chart colours.

    Returns
    -------
    list
        ``n`` colours, in series order.
    """
    if palette is None:
        if n > len(CHART_COLOURS):
            raise ValueError(
                f"{n} categorical series is more than the {len(CHART_COLOURS)} chart colours: group the smallest "
                "categories, use small multiples or label series directly, or pass a matplotlib palette"
            )
        return list(CHART_COLOURS[:n])
    cmap = plt.get_cmap(palette)
    if cmap.N >= 256:
        return [cmap(i / max(n - 1, 1)) for i in range(n)]
    return [cmap(i % cmap.N) for i in range(n)]


def sequential_palette(n: int) -> list[str]:
    """Return ``n`` ordered colours for amounts that run from least to most.

    Step 1 is the least and the lightest. Each step reaches 3:1 against
    :data:`BACKGROUND_COLOUR`, so draw neighbouring segments, such as the parts
    of a stacked bar, with ``edgecolor=BACKGROUND_COLOUR`` to keep a gap between
    them. Use :data:`SEQUENTIAL_CMAP` for a continuous scale.

    Parameters
    ----------
    n : int
        Number of ordered values, from 3 to 5.

    Returns
    -------
    list[str]
        ``n`` hex colours, least first.
    """
    return _ordered(SEQUENTIAL_PALETTES, "sequential", n)


def diverging_palette(n: int) -> list[str]:
    """Return ``n`` ordered colours for values either side of a midpoint.

    The colours run from the low or negative end, in orange, to the high or
    positive end, in blue; an odd ``n`` has a grey middle step. Survey answers
    listed from most to least positive take the colours in reverse. Each step
    reaches 3:1 against :data:`BACKGROUND_COLOUR`, so draw neighbouring
    segments with ``edgecolor=BACKGROUND_COLOUR``. Use :data:`DIVERGING_CMAP` for
    a continuous scale, such as correlations.

    Parameters
    ----------
    n : int
        Number of ordered values, from 3 to 5.

    Returns
    -------
    list[str]
        ``n`` hex colours, low end first.
    """
    return _ordered(DIVERGING_PALETTES, "diverging", n)


def _ordered(palettes: dict[int, tuple[str, ...]], kind: str, n: int) -> list[str]:
    if n not in palettes:
        sizes = ", ".join(str(k) for k in sorted(palettes))
        raise ValueError(f"no {kind} palette with {n} steps; the design tokens have {sizes}")
    return list(palettes[n])
