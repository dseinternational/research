def _load_design_tokens() -> dict:
    """The light colours from the DSE design tokens: ``design_tokens/colors.json``, generated by
    dsegroup/apps-common and pinned in ``design_tokens/design-tokens.pin.json``. Figures are light."""
    source = resources.files("dse_research_utils.plot").joinpath("design_tokens", "colors.json")
    return json.loads(source.read_text(encoding="utf-8"))["light"]


_TOKENS = _load_design_tokens()

CHART_COLOURS: tuple[str, ...] = tuple(_TOKENS["categorical"])
"""``chart-1`` to ``chart-6``: categorical series, in order."""

TEXT_COLOUR: str = _TOKENS["foreground"]
"""Text, ticks and labels."""

