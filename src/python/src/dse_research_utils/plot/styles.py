def __getattr__(name: str) -> str:
    if name in _DEPRECATED_COLOURS:
        value, replacement = _DEPRECATED_COLOURS[name]
        warnings.warn(
            f"styles.{name} is deprecated: use {replacement}, in series order, or a sequential or diverging step "
            "for ordered values.",
            DeprecationWarning,
            stacklevel=2,
        )
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


