"""A continuous scale through the five-step diverging set, registered as ``dse_diverging``."""

for _cmap in (SEQUENTIAL_CMAP, DIVERGING_CMAP, SEQUENTIAL_CMAP.reversed(), DIVERGING_CMAP.reversed()):
    if _cmap.name not in mpl.colormaps:
        mpl.colormaps.register(_cmap)

